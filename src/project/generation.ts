/**
 * Generated-track provenance: which part wrote a track, from which seed, under
 * which library algorithm version.
 *
 * Without a record of that, "this track was generated" can only be guessed at,
 * and the guess available is the track's display name — which the user is free
 * to change, and free to give to a track they played by hand. The record makes
 * the classification durable in the same way {@link EditorTrack.percussion}
 * makes the drum classification durable: the name heuristic stays, but only as
 * the fallback for tracks written before a record existed.
 *
 * `algorithmVersion` is recorded provenance: the libcantus algorithm version the
 * track was written under. Nothing reads it back to regenerate the part.
 *
 * Pure module: no store access, no wasm.
 */

import { ALGORITHM_VERSION, deriveSeed } from '@libraz/libcantus';

/** The five instrumental parts the generation commands can write. */
export type TrackPart = 'motif' | 'drums' | 'bass' | 'counter' | 'backing';

/** Every part, in the order the generate dialog lists them. */
export const TRACK_PARTS: ReadonlyArray<TrackPart> = [
  'motif',
  'drums',
  'bass',
  'counter',
  'backing',
];

/** Canonical generated-track name per part, used by the name fallback. */
export const PART_TRACK_NAMES: Readonly<Record<TrackPart, string>> = {
  motif: 'Motif',
  drums: 'Drums',
  bass: 'Bass',
  counter: 'Counter melody',
  backing: 'Backing',
};

/** How a track was generated, recorded as provenance. */
export interface TrackProvenance {
  /** The part that wrote the track. */
  part: TrackPart;
  /** The seed handed to the generator. */
  seed: number;
  /** The library algorithm version the notes were written under. */
  algorithmVersion: number;
}

/** The algorithm version this build generates under by default. */
export const CURRENT_ALGORITHM_VERSION: number = ALGORITHM_VERSION;

/** Builds the provenance record for a part generated by this build. */
export function trackProvenance(part: TrackPart, seed: number): TrackProvenance {
  return { part, seed, algorithmVersion: CURRENT_ALGORITHM_VERSION };
}

function isTrackPart(value: unknown): value is TrackPart {
  return typeof value === 'string' && (TRACK_PARTS as ReadonlyArray<string>).includes(value);
}

/**
 * Reads a provenance record out of untrusted document data.
 *
 * A record naming a part this build does not know, or carrying a non-integer
 * seed or version, is dropped rather than repaired: a half-read record would
 * claim a reproducibility it cannot deliver, and dropping it only falls back to
 * the name heuristic.
 *
 * @param value The candidate value from a loaded document.
 * @returns The record, or undefined when there is not a whole one.
 */
export function sanitizeProvenance(value: unknown): TrackProvenance | undefined {
  if (value === null || typeof value !== 'object') return undefined;
  const raw = value as Partial<Record<keyof TrackProvenance, unknown>>;
  if (!isTrackPart(raw.part)) return undefined;
  if (!Number.isInteger(raw.seed) || !Number.isInteger(raw.algorithmVersion)) return undefined;
  const seed = raw.seed as number;
  const algorithmVersion = raw.algorithmVersion as number;
  if (seed < 0 || algorithmVersion < 1) return undefined;
  return { part: raw.part, seed, algorithmVersion };
}

/** Largest project seed; seeds are 32-bit unsigned integers. */
export const MAX_GENERATION_SEED = 0xffffffff;

/**
 * Coerces a project seed to the 32-bit unsigned integer the derivation needs.
 * Anything unreadable becomes 0, which is a valid seed rather than an error.
 */
export function normalizeGenerationSeed(value: unknown): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) return 0;
  const rounded = Math.round(value);
  if (rounded <= 0) return 0;
  return Math.min(rounded, MAX_GENERATION_SEED);
}

/**
 * The seed a part generates from, addressed by name under the project seed.
 *
 * One number for the project is what makes a piece reproducible; addressing
 * each part beneath it is what makes a part rerollable on its own. Bumping the
 * trailing counter gives that part unrelated material and leaves every other
 * part on the seed it already had, because their paths did not change.
 *
 * @param projectSeed The project seed (coerced by {@link normalizeGenerationSeed}).
 * @param path Where the part sits, e.g. the part name then its reroll counter.
 * @returns A 32-bit seed for that path.
 */
export function partSeed(projectSeed: number, ...path: ReadonlyArray<string | number>): number {
  return deriveSeed(normalizeGenerationSeed(projectSeed), ...path);
}

/** The track fields {@link partForTrack} classifies from. */
export interface ClassifiableTrack {
  name: string;
  generated?: TrackProvenance;
}

/**
 * Classifies a track as a generated part, so it can be offered as a
 * regeneration target.
 *
 * A recorded origin wins outright: it survives a rename, and it never claims a
 * hand-played track. Only a track with no record falls back to matching the
 * canonical part name, which is what tracks generated before the record existed
 * have to be recognised by.
 *
 * @param track The track to classify.
 * @returns The part that wrote it, or null when nothing says one did.
 */
export function partForTrack(track: ClassifiableTrack): TrackPart | null {
  if (track.generated !== undefined) return track.generated.part;
  const normalized = track.name.trim().toLowerCase();
  for (const part of TRACK_PARTS) {
    if (PART_TRACK_NAMES[part].toLowerCase() === normalized) return part;
  }
  return null;
}
