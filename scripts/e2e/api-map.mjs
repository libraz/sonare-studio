/**
 * The libsonare API-to-scenario map: which scenario reaches which libsonare
 * call through the UI. The rows are libsonare's own surface, enumerated from
 * the installed package, so a call no scenario reaches shows up as a row with
 * no scenarios; the cells are what the recording build reported per scenario.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const API_MAP_PATH = fileURLToPath(new URL('./api-map.md', import.meta.url));

const isClass = (value, name) =>
  typeof value === 'function' && /^[A-Z]/.test(name) && value.prototype !== undefined;

const SKIPPED_STATICS = new Set(['length', 'name', 'prototype', 'caller', 'arguments']);

function classSurface(name, cls) {
  const keys = [`new ${name}`];
  for (const key of Object.getOwnPropertyNames(cls)) {
    if (!SKIPPED_STATICS.has(key) && typeof cls[key] === 'function') keys.push(`${name}.${key}`);
  }
  for (let proto = cls.prototype; proto && proto !== Object.prototype; ) {
    for (const key of Object.getOwnPropertyNames(proto)) {
      const descriptor = Object.getOwnPropertyDescriptor(proto, key);
      if (key !== 'constructor' && typeof descriptor?.value === 'function') {
        keys.push(`${name}#${key}`);
      }
    }
    proto = Object.getPrototypeOf(proto);
  }
  return keys;
}

/** Every call the recording build can report, grouped by section. */
async function librarySurface() {
  const sonare = await import('@libraz/libsonare');
  const { SonareEngine } = await import('@libraz/libsonare/worklet');
  const functions = [];
  const classes = new Map();
  for (const name of Object.keys(sonare)) {
    const value = sonare[name];
    if (isClass(value, name)) classes.set(name, classSurface(name, value));
    else if (typeof value === 'function') functions.push(name);
  }
  classes.set('SonareEngine', classSurface('SonareEngine', SonareEngine).slice(1));
  return { functions, classes };
}

const cell = (scenarios) => (scenarios.length === 0 ? '—' : scenarios.join(', '));

function table(keys, reachedBy) {
  const rows = [...new Set(keys)].sort().map((key) => {
    const scenarios = [...(reachedBy.get(key) ?? [])].sort();
    return `| \`${key}\` | ${cell(scenarios)} |`;
  });
  return ['| Call | Scenarios |', '| --- | --- |', ...rows].join('\n');
}

/**
 * Renders the map from per-scenario call lists.
 *
 * @param {{ name: string, apiCalls: string[] }[]} outcomes
 * @returns {Promise<string>} The markdown document.
 */
export async function renderApiMap(outcomes) {
  const reachedBy = new Map();
  for (const outcome of outcomes) {
    for (const key of outcome.apiCalls) {
      if (!reachedBy.has(key)) reachedBy.set(key, new Set());
      reachedBy.get(key).add(outcome.name);
    }
  }
  const { functions, classes } = await librarySurface();
  const listed = new Set([...functions, ...[...classes.values()].flat()]);
  const unlisted = [...reachedBy.keys()].filter((key) => !listed.has(key));
  const reachedCount = (keys) => keys.filter((key) => reachedBy.has(key)).length;

  const sections = [
    `## Module functions\n\n${reachedCount(functions)} of ${functions.length} reached.\n\n${table(functions, reachedBy)}`,
  ];
  for (const [name, keys] of [...classes].sort(([a], [b]) => a.localeCompare(b))) {
    sections.push(
      `## \`${name}\`\n\n${reachedCount(keys)} of ${keys.length} reached.\n\n${table(keys, reachedBy)}`,
    );
  }
  if (unlisted.length > 0) sections.push(`## Other calls\n\n${table(unlisted, reachedBy)}`);

  return `# libsonare API map

Generated by the full end-to-end run (\`yarn e2e\`); do not edit. A full run fails when this file no longer matches what the scenarios reach, and \`yarn e2e --update-api-map\` rewrites it.

Each row is a call on libsonare's public surface and the scenarios that reach it through the UI. A call counts when the app makes it on the main thread through the module \`ensureWasm\` returns, an instance a class of that module created, or the realtime engine facade. These are not recorded, so a row can read — while the call still runs:

- calls made inside workers (the export and notation workers) and inside the AudioWorklet;
- reads of exported constants and enum tables, such as the synth option lists;
- functions and classes imported statically rather than through \`ensureWasm\`, such as \`isSonareError\` and \`ClipPageProvider\`.

${sections.join('\n\n')}
`;
}

/**
 * Compares the rendered map with the committed one, or rewrites it.
 *
 * @returns {Promise<boolean>} Whether the committed map matched (always true when rewriting).
 */
export async function checkApiMap(outcomes, { update }) {
  const rendered = await renderApiMap(outcomes);
  if (update) {
    await writeFile(API_MAP_PATH, rendered);
    console.info(`api map written to ${API_MAP_PATH}`);
    return true;
  }
  const committed = await readFile(API_MAP_PATH, 'utf8').catch(() => '');
  if (committed === rendered) return true;
  const lines = (text) => new Set(text.split('\n'));
  const before = lines(committed);
  const after = lines(rendered);
  const changed = [
    ...[...after].filter((line) => !before.has(line)).map((line) => `+ ${line}`),
    ...[...before].filter((line) => !after.has(line)).map((line) => `- ${line}`),
  ];
  console.error(
    `api map drift: the scenarios reach a different set of calls than ${API_MAP_PATH} records; ` +
      `run yarn e2e --update-api-map and commit the result\n${changed.slice(0, 40).join('\n')}`,
  );
  return false;
}
