/**
 * Harvests the outlines of the SMuFL glyphs Verovio writes as text (a Leipzig
 * <tspan>) so the PDF path can draw them as paths. Verovio emits these code
 * points inside text for metronome marks (ECA0-ECBF), chord-symbol accidentals
 * (EA50-EA6F) and lyric elisions (E550-E55F); a code point Leipzig lacks is
 * left out. Outlines are in font units, 1000 per em, y up.
 *
 * `node scripts/smufl-text-glyphs.mjs` rewrites src/notation/smufl-text-glyphs.ts.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { VerovioToolkit } from 'verovio/esm';
import createVerovioModule from 'verovio/wasm';

export const SMUFL_TEXT_RANGES = [
  [0xe550, 0xe55f],
  [0xea50, 0xea6f],
  [0xeca0, 0xecbf],
];

const hex = (codePoint) => codePoint.toString(16).toUpperCase();

/** @returns {Promise<Map<number, string>>} Code point to outline path data. */
export async function harvestSmuflTextGlyphs() {
  const toolkit = new VerovioToolkit(await createVerovioModule());
  const codePoints = SMUFL_TEXT_RANGES.flatMap(([first, last]) =>
    Array.from({ length: last - first + 1 }, (_, index) => first + index),
  );
  // A fermata carrying glyph.num is drawn from the music font's outline, which
  // lands in <defs> once per code point.
  const fermatas = codePoints
    .map((cp) => `<fermata tstamp="1" staff="1" glyph.auth="smufl" glyph.num="U+${hex(cp)}"/>`)
    .join('');
  toolkit.setOptions({ inputFrom: 'mei' });
  toolkit.loadData(
    '<?xml version="1.0"?><mei xmlns="http://www.music-encoding.org/ns/mei" meiversion="5.0">' +
      '<meiHead><fileDesc><titleStmt><title/></titleStmt><pubStmt/></fileDesc></meiHead>' +
      '<music><body><mdiv><score><scoreDef><staffGrp><staffDef n="1" lines="5" clef.shape="G" clef.line="2"/>' +
      '</staffGrp></scoreDef><section><measure n="1"><staff n="1"><layer n="1"><note pname="c" oct="4" dur="1"/>' +
      `</layer></staff>${fermatas}</measure></section></score></mdiv></body></music></mei>`,
  );
  const svg = toolkit.renderToSVG(1);
  const outlines = new Map();
  for (const match of svg.matchAll(
    /<g id="(E[0-9A-F]{3})-[^"]*">\s*<path transform="scale\(1,-1\)" d="([^"]*)"/g,
  )) {
    const codePoint = Number.parseInt(match[1], 16);
    if (codePoints.includes(codePoint)) outlines.set(codePoint, match[2].trim());
  }
  return new Map([...outlines].sort(([a], [b]) => a - b));
}

/** Renders the generated module for a harvested outline table. */
export function renderSmuflTextGlyphModule(outlines) {
  const rows = [...outlines]
    .map(([codePoint, d]) => `  [0x${codePoint.toString(16)}, '${d}'],`)
    .join('\n');
  return `// Generated by scripts/smufl-text-glyphs.mjs from Verovio's Leipzig outlines; do not edit.

/** Outline path data of the SMuFL glyphs Verovio writes as text, in font units (1000 per em, y up). */
export const SMUFL_TEXT_GLYPHS: ReadonlyMap<number, string> = new Map([
${rows}
]);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputPath = fileURLToPath(
    new URL('../src/notation/smufl-text-glyphs.ts', import.meta.url),
  );
  const outlines = await harvestSmuflTextGlyphs();
  writeFileSync(outputPath, renderSmuflTextGlyphModule(outlines));
  console.info(`wrote ${outlines.size} outlines to ${outputPath}`);
}
